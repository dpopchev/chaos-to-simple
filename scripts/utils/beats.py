"""The section beats as LaTeX: the believed line and the agenda strip of each section."""

from __future__ import annotations

from collections.abc import Sequence

from scripts.utils.lines import Line

STRIP_DIR = "build/00-frontmatter"


def _define(name: str, number: int, value: str) -> str:
    return f"\\expandafter\\gdef\\csname {name}@{number}\\endcsname{{{value}}}"


def beats_tex(lines: Sequence[Line]) -> str:
    """Return one believed@n and one strip@n definition per line, n from 1.

    >>> beats_tex([Line("01-bits", "B", "L")]).splitlines()[1]
    '\\\\expandafter\\\\gdef\\\\csname believed@1\\\\endcsname{B}'
    """
    rows = ["% Generated by scripts/beats_tex.py from data/lines.csv."]
    for number, line in enumerate(lines, start=1):
        rows.append(_define("believed", number, line.believed))
        rows.append(_define("strip", number, f"{STRIP_DIR}/agenda-{number:02d}.png"))
    return "\n".join(rows) + "\n"
